"""Generates rust/crates/livedaw-dsp/src/x32/fx_models.rs from the X32 FX catalogue
(x32fx_catalogue.json, transcribed from the public OSC protocol document) and
the factory values of the owner's X32 Compact (the read-only snapshot).

Usage: gen_fx_models.py tools/x32/fx_catalogue.json SNAPSHOT rust/crates/livedaw-dsp/src/x32/fx_models.rs rust/crates/livedaw-dsp/src/wing/models_gen.rs

fx_catalogue.json: the 61 models' parameters as the public OSC protocol document lists them
(transcribed and checked against each model's type signature). SNAPSHOT: a read-only
`/node` dump of a freshly initialised X32 (kept outside the repository).

"""
import json
import re
import sys

cat = json.load(open(sys.argv[1]))
snap = {}
for line in open(sys.argv[2], encoding='utf-8'):
    if line.startswith('/fx/'):
        snap[line.split(' ')[0]] = line.split()[1:]

# FX 5-8 take these (the X32's insert models); the rest need FX 1-4.
INSERT = ['GEQ2', 'GEQ', 'TEQ2', 'TEQ', 'DES2', 'DES', 'P1A', 'P1A2', 'PQ5', 'PQ5S', 'WAVD', 'LIM', 'FAC', 'FAC1M', 'FAC2',
          'LEC', 'LEC2', 'ULC', 'ULC2', 'ENH2', 'ENH', 'EXC2', 'EXC', 'IMG', 'EDI', 'SON', 'AMP2', 'AMP', 'DRV2', 'DRV', 'PHAS',
          'FILT', 'PAN', 'SUB']
# Where the owner's X32 holds values outside the document's range.
WIDEN = {('VRM', 3): (0, 100), ('VRM', 11): (0, 100), ('VRM', 12): (0, 100)}


def num(t):
    t = t.strip()
    if 'k' in t:
        a, b = t.split('k')
        return float(a or 0) * 1000 + (float('0.' + b) * 1000 if b else 0)
    return float(t)


def unit(p):
    n = p['name'].lower()
    if p['type'] == 'enum':
        return ''
    lo, hi = min(p['min'], p['max']), max(p['min'], p['max'])
    if p['type'] == 'logf' and hi >= 1000 and any(k in n for k in ('cut', 'damp', 'freq', 'xover', 'tune', 'base', 'f ')):
        return 'Hz'
    if p['type'] == 'logf' and hi >= 200 and any(k in n for k in ('cut', 'xover', 'freq')):
        return 'Hz'
    if 'speed' in n or 'rate' in n:
        return 'Hz'
    if 'decay' in n and hi <= 30:
        return 's'
    if any(k in n for k in ('delay', 'time', 'echo l', 'echo r', 'reflection l', 'reflection r', 'attack', 'release', 'hold')) and 'gain' not in n:
        return 'ms'
    if any(k in n for k in ('level', 'gain', 'threshold', 'thr', 'master')) and lo < 0:
        return 'dB'
    if 'band' in n and lo == -15:
        return 'dB'
    return ''


def slug(name):
    s = re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')
    return s or 'p'


def default(code, p, factory):
    if factory is not None:
        v = factory[p['n'] - 1]
        if p['type'] == 'enum':
            return float(p['items'].index(v)) if v in p['items'] else float(v)
        return num(v)
    n = p['name'].lower()
    if p['type'] == 'enum':
        items = p['items']
        if items == ['OFF', 'ON']:
            # Dimension Chorus with its first mode pressed (none: no effect).
            return 1.0 if n.startswith('active') or (code == 'DIMC' and n == 'mode 1') else 0.0
        return 0.0
    lo, hi = p['min'], p['max']
    if min(lo, hi) < 0 < max(lo, hi):
        return 0.0
    if n.startswith('mix'):
        return hi
    if p['type'] == 'logf':
        return round((lo * hi) ** 0.5, 3)
    return round(lo + (hi - lo) / 2, 3)


def steps(p, lo, hi):
    # Fine enough that the X32's own values (its floats are 0..1, not steps)
    # land on one: whole numbers on whole-number scales, half dB on dB.
    if p['type'] == 'enum':
        return len(p['items'])
    span = abs(hi - lo)
    if p['type'] == 'logf':
        return 10001
    if unit(p) == 'dB':
        return int(span * 2) + 1 if span == int(span) else 1001
    return int(span) + 1 if span == int(span) and span >= 2 else 1001


def rs(x):
    s = repr(float(x))
    return s if '.' in s or 'e' in s else s + '.0'


factory = {}
for slot in range(1, 9):
    factory.setdefault(snap[f'/fx/{slot}'][0], snap[f'/fx/{slot}/par'])

out = []
out.append('// Generated by tools/x32/gen_fx_models.py from the X32 OSC protocol document\'s parameter maps')
out.append('// (pp. 85-115) and a freshly initialised X32 Compact\'s factory FX values. Do not edit by hand.')
out.append('use crate::model::{ModelCategory, ModelSpec, ParamKind, ParamSpec};')
out.append('')
choices = {}
for m in cat:
    code = m['code']
    ident = re.sub(r'[^A-Z0-9]', '_', code)
    if ident[0].isdigit():
        ident = 'M' + ident
    fac = factory.get(code)
    rows = []
    seen = {}
    for p in m['params']:
        lo, hi = WIDEN.get((code, p['n']), (p.get('min'), p.get('max')))
        if p['type'] == 'enum':
            items = p['items']
            if items == ['OFF', 'ON']:
                kind = 'ParamKind::Toggle'
            else:
                key = tuple(items)
                if key not in choices:
                    choices[key] = f'CHOICE_{len(choices)}'
                kind = f'ParamKind::Choice({choices[key]})'
            lo, hi = 0.0, float(len(items) - 1)
        else:
            kind = 'ParamKind::Log' if p['type'] == 'logf' else 'ParamKind::Linear'
        sid = slug(p['name'])
        seen[sid] = seen.get(sid, 0) + 1
        if seen[sid] > 1:
            sid = f'{sid}_{seen[sid]}'
        d = default(code, p, fac)
        d = min(max(d, min(lo, hi)), max(lo, hi))
        rows.append(f'    p("{sid}", "{p["name"].upper()}", "{unit(p)}", {kind}, {rs(lo)}, {rs(hi)}, {steps(p, lo, hi)}, {rs(d)}),')
    out.append(f'/// {m["title"]} (`{code}`, {len(rows)} parameters).')
    out.append(f'const {ident}: &[ParamSpec] = &[')
    out.extend(rows)
    out.append('];')
    out.append('')
    m['ident'] = ident

choice_lines = []
for items, name in choices.items():
    choice_lines.append(f'const {name}: &[&str] = &[' + ', '.join(f'"{i}"' for i in items) + '];')
out[4:4] = choice_lines + ['']

out.append('#[allow(clippy::too_many_arguments)]')
out.append('const fn p(id: &\'static str, label: &\'static str, unit: &\'static str, kind: ParamKind, min: f32, max: f32, steps: u32, default: f32) -> ParamSpec {')
out.append('    ParamSpec { id, label, unit, kind, min, max, steps, default }')
out.append('}')
out.append('')
# The empty slot and the plugin slot (EXT) are the WING's, copied from its table.
wing = open(sys.argv[4], encoding='utf-8').read().split('\n')
start = next(i for i, l in enumerate(wing) if l == '        token: "EXT",') - 1
end = next(i for i in range(start, len(wing)) if wing[i] == '    },')
out.append('/// The X32\'s FX rack: an empty slot, a plugin (EXT, as the WING\'s), then its 61 models in its')
out.append('/// FX 1-4 order (`/fx/N/type` 0-60), each `X32` + its code.')
out.append('pub static FX_MODELS: &[ModelSpec] = &[')
out.append('    ModelSpec { token: "NONE", name: "None", category: ModelCategory::FxNone, params: &[] },')
out.extend(wing[start:end + 1])
for m in cat:
    catg = 'FxStandard' if m['code'] in INSERT else 'FxPremium'
    out.append(f'    ModelSpec {{ token: "X32{m["code"]}", name: "{m["title"]}", category: ModelCategory::{catg}, params: {m["ident"]} }},')
out.append('];')
out.append('')
out.append('/// The FX 5-8 models (their own `/fx/N/type` 0-33), by code.')
out.append('pub const INSERT_ORDER: [&str; 34] = [' + ', '.join(f'"{c}"' for c in INSERT) + '];')
open(sys.argv[3], 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print('models', len(cat), 'choices', len(choices))
with open(sys.argv[3], 'a', encoding='utf-8', newline='\n') as f:
    f.write('\n/// The FX 1-4 models (`/fx/N/type` 0-60), by code.\n')
    f.write('pub const CODES: [&str; 61] = [' + ', '.join(f'"{m["code"]}"' for m in cat) + '];\n')
